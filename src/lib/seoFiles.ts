function xmlEscape(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

/** Dashes in copied page text become plain hyphens so the AI-facing files stay simple ASCII punctuation. */
function plain(text: string): string {
  return text.replace(new RegExp(" ?[" + String.fromCharCode(0x2013, 0x2014) + "] ?", "g"), " - ");
}

function stripQuery(url: string): string {
  return url.replace(/\?.*$/, "");
}

/* ------------------------------------------------------------------------------------------------ */
/* sitemap.xml                                                                                       */
/* ------------------------------------------------------------------------------------------------ */

export function buildSitemapXml(routes: RouteSeo[] = indexableRoutes()): string {
  const blocks = routes.map((r) => {
    const image = r.ogImage ?? `${SITE_URL}/og-image.png`;
    const imageTitle = plain(r.ogImageAlt ?? r.title);
    return `  <url>
    <loc>${xmlEscape(pageUrl(r.path))}</loc>
    <lastmod>${r.dateModified}</lastmod>
    <changefreq>${r.changefreq ?? "monthly"}</changefreq>
    <priority>${(r.priority ?? 0.5).toFixed(1)}</priority>
    <image:image>
      <image:loc>${xmlEscape(stripQuery(image))}</image:loc>
      <image:title>${xmlEscape(imageTitle)}</image:title>
    </image:image>
  </url>`;
  });
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${blocks.join("\n\n")}
</urlset>
`;
}

