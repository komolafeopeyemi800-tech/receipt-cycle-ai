/** Paths crawlers must not fetch: signed-in app screens, auth flows and API. */
export function robotsDisallowPaths(): string[] {
  return [...PRIVATE_ROUTE_PATHS, "/oauth/", "/auth/", "/api/"];
}

export function buildRobotsTxt(): string {
  const disallow = robotsDisallowPaths().map((p) => `Disallow: ${p}`);
  const group = (title: string, agents: string[]) =>
    [`# ${title}`, ...agents.map((a) => `User-agent: ${a}`), "Allow: /", ...disallow].join("\n");
  return `# Receipt Cycle robots.txt (generated by scripts/generate-seo-assets.mjs; edit src/lib/seoFiles.ts).
# Public marketing, blog, pricing, FAQ and policy pages are open to search engines and AI crawlers.
# The signed-in app, auth flows and API are closed to everyone.
# AI-friendly summaries: ${SITE_URL}/llms.txt and ${SITE_URL}/llms-full.txt
# If you add Cloudflare, also disable "Block AI Scrapers and Crawlers" and keep Super Bot Fight Mode
# off (or allow "verified bots") or the rules below are overridden at the edge.
# A crawler that matches a named group ignores the "*" group, so every group repeats the Disallow list.

${group("Search engines", SEARCH_BOTS)}

${group("Social preview fetchers", SOCIAL_BOTS)}

${group("AI search, answer engines and model crawlers", AI_BOTS)}

${group("Everyone else", ["*"])}

Sitemap: ${SITE_URL}/sitemap.xml
`;
}

