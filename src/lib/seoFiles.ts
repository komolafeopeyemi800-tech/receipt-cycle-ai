/* llms-full.txt                                                                                     */
/* ------------------------------------------------------------------------------------------------ */

export function buildLlmsFullTxt(): string {
  const routes = indexableRoutes();
  const updated = latestDate(routes);
  const out: string[] = [];
  const push = (...l: string[]) => out.push(...l);

  push(
    "# Receipt Cycle: full content for AI systems",
    "",
    `> ${PRODUCT_SUMMARY}`,
    "",
    `Source: ${SITE_URL}/ | Last updated: ${updated} | Contact: ${SUPPORT_EMAIL}`,
    "This file is generated from the same content as the public pages. The page URLs below are canonical.",
    "",
    "## Product overview",
    "",
    `Receipt Cycle (trade name of ${LEGAL_NAME}) helps freelancers, independent professionals, and small businesses keep the records behind everyday spending and customer billing in one place.`,
    "It is available as a web app and an Android app that share one account. No iOS app is published.",
    "",
    "Features:",
    ...APP_FEATURES.map((f) => `- ${f}`),
    "",
    "What it is not:",
    ...LIMITS.map((l) => `- ${l}`),
    "",
    "## How it works",
    "",
    "1. Capture: photograph or upload a receipt, or enter a transaction by hand. AI proposes the merchant, date, total, tax, and line items, and you review them before saving.",
    "2. Organize: saved transactions get categories and accounts. Customers and a catalog of products and services are stored for billing.",
    "3. Bill: prepare estimates, convert accepted work into invoices, and record full or partial payments with receipts.",
    "4. Review: compare monthly category budgets with recorded spending, open reports, and ask questions about the saved records.",
    "",
    "## Pricing",
    "",
    `Source: ${pageUrl("/pricing")}`,
    "",
    ...pricingLines(),
    "",
  );

  push("## Feature pages", "");
  for (const lp of LANDING_PAGES) {
    push(
      `### ${lp.name}`,
      "",
      `URL: ${pageUrl(lp.path)} | Last updated: ${lp.dateModified}`,
      "",
      lp.description,
      "",
      "Covers:",
      ...lp.featureList.map((f) => `- ${f}`),
      "",
      "Questions and answers:",
      "",
    );
    for (const f of landingFaqs(lp.path)) push(`**${f.q}**`, f.a, "");
  }

  push("## Frequently asked questions", "", `Source: ${pageUrl("/faq")}`, "");
  for (const f of SITE_FAQ_ITEMS) push(`**${f.q}**`, f.a, "");

  const homeFaq = landingFaqs("/");
  if (homeFaq.length) {
    push("## Home page questions", "", `Source: ${pageUrl("/")}`, "");
    for (const f of homeFaq) push(`**${f.q}**`, f.a, "");
  }

  push("## Blog articles", "", `Index: ${pageUrl("/blog")}`, "");
  for (const p of BLOG_POSTS) {
    push(
      `### ${p.title}`,
      "",
      `URL: ${pageUrl(`/blog/${p.slug}`)} | Published: ${p.datePublished} | Updated: ${p.dateModified} | ${p.readMinutes} min read`,
      "",
      p.description,
      "",
      `Summary: ${p.tldr}`,
      "",
    );
  }

  push("## Company and policies", "");
  const about = getRouteSeo("/about");
  if (about) push(`- About: ${pageUrl("/about")}. ${about.description}`);
  push(
    `- Contact: ${pageUrl("/contact")}. Email ${SUPPORT_EMAIL}; replies within one business day.`,
    `- Privacy Policy: ${pageUrl("/privacy")}`,
    `- Terms of Service: ${pageUrl("/terms")}`,
    `- Refund Policy: ${pageUrl("/refund-policy")}`,
    `- Cookie Policy: ${pageUrl("/cookies")}`,
    `- Delete your account: ${pageUrl("/delete-account")}`,
    "",
    "## How to cite",
    "",
    `Cite the canonical page URL and name the source as "Receipt Cycle". For prices and plan details use ${pageUrl("/pricing")}.`,
    "",
  );

  return plain(out.join("\n"));
}
