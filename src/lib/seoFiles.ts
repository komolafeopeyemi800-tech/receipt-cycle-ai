function latestDate(routes: RouteSeo[]): string {
  return routes.reduce((max, r) => ((r.dateModified ?? "") > max ? (r.dateModified as string) : max), "0000-00-00");
}

function link(title: string, path: string, description: string): string {
  return `- [${title}](${pageUrl(path)}): ${description}`;
}

